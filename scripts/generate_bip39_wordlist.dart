// Generates lib/src/mnemonic/bip39_english_wordlist.dart from the
// official BIP-39 English wordlist.
//
// The download is checked against the SHA-256 of the official file; if
// it does not match, nothing is written.
//
// Usage, from the project root:
// ```sh
// dart run scripts/generate_bip39_wordlist.dart
// dart format lib/src/mnemonic/
// ```

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:pointycastle/digests/sha256.dart';

const _sourceUrl =
    'https://raw.githubusercontent.com/bitcoin/bips/master/bip-0039/english.txt';
const _specUrl =
    'https://github.com/bitcoin/bips/blob/master/bip-0039.mediawiki';
const _expectedSha256 =
    '2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda';
const _expectedWordCount = 2048;
const _outputPath = 'lib/src/mnemonic/bip39_english_wordlist.dart';

Future<void> main() async {
  final client = HttpClient();
  try {
    // Download the official wordlist.
    final request = await client.getUrl(Uri.parse(_sourceUrl));
    final response = await request.close();
    if (response.statusCode != 200) {
      stderr.writeln('Download failed: HTTP ${response.statusCode}.');
      exit(1);
    }
    final builder = BytesBuilder(copy: false);
    await response.forEach(builder.add);
    final bytes = builder.takeBytes();

    // Refuse anything that is not byte-for-byte the official file.
    final hash = SHA256Digest().process(Uint8List.fromList(bytes));
    final hashHex =
        hash.map((byte) => byte.toRadixString(16).padLeft(2, '0')).join();
    if (hashHex != _expectedSha256) {
      stderr.writeln(
        'SHA-256 mismatch: expected $_expectedSha256, got $hashHex.',
      );
      exit(1);
    }

    final words = const LineSplitter()
        .convert(utf8.decode(bytes))
        .where((word) => word.isNotEmpty)
        .toList();
    if (words.length != _expectedWordCount) {
      stderr.writeln(
        'Expected $_expectedWordCount words, got ${words.length}.',
      );
      exit(1);
    }

    // Write the Dart source, one word per line.
    final output = StringBuffer()
      ..writeln('// GENERATED by scripts/generate_bip39_wordlist.dart.')
      ..writeln('// Do not edit by hand.')
      ..writeln('//')
      ..writeln('// Source: $_sourceUrl')
      ..writeln('// SHA-256: $_expectedSha256')
      ..writeln()
      ..writeln(
        '/// The official BIP-39 English wordlist: $_expectedWordCount words,',
      )
      ..writeln(
        '/// sorted alphabetically. The index of a word (0 to 2047) is the',
      )
      ..writeln('/// 11-bit value it encodes in a mnemonic.')
      ..writeln('///')
      ..writeln('/// See: $_specUrl')
      ..writeln('const List<String> bip39EnglishWordlist = [');
    for (final word in words) {
      output.writeln("  '$word',");
    }
    output.writeln('];');

    File(_outputPath)
      ..createSync(recursive: true)
      ..writeAsStringSync(output.toString());
    stdout.writeln('Wrote ${words.length} words to $_outputPath.');
  } finally {
    client.close();
  }
}
